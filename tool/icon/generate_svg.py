"""Draws tool/icon/mise.svg, Mise's app icon: the author's scruffy white
terrier, one blue eye (left) and one brown.

The fur tufts are generated, so tweak them here and run:
    python3 tool/icon/generate_svg.py && tool/icon/render.sh
"""
import pathlib
import math, random

def spiky(cx, cy, rx, top, bottom, n, seed, out=1.14, inn=0.95, droop=0.16):
    """Head outline made of pointed tufts that droop downwards, longer on
    the cheeks and beard than on the crown."""
    rnd = random.Random(seed)
    def base(t, k):
        c, s = math.cos(t), math.sin(t)
        e = 2.4
        ry = top if s < 0 else bottom
        return (cx + rx * k * math.copysign(abs(c) ** (2 / e), c),
                cy + ry * k * math.copysign(abs(s) ** (2 / e), s))
    d = ''
    for i in range(n):
        t0 = 2 * math.pi * i / n - math.pi / 2
        t1 = 2 * math.pi * (i + 1) / n - math.pi / 2
        tm = (t0 + t1) / 2
        # Longer tufts where fur hangs (sides, beard), short on the crown.
        hang = 0.35 + 0.65 * (1 - max(0.0, -math.sin(tm)))
        k = 1 + (out - 1) * hang * (1 + rnd.uniform(-0.2, 0.2))
        # Tips droop: pushed down and towards the bottom.
        tip = base(tm + droop * math.cos(tm) * (1 if math.sin(tm) > -0.6 else 0), k)
        a = base(t0, inn)
        b = base(t1, inn)
        if i == 0:
            d += f'M{a[0]:.1f} {a[1]:.1f}'
        ca = ((a[0] + tip[0]) / 2 + (b[0] - a[0]) * 0.18, (a[1] + tip[1]) / 2 + (b[1] - a[1]) * 0.18)
        cb = ((b[0] + tip[0]) / 2, (b[1] + tip[1]) / 2)
        d += f' Q{ca[0]:.1f} {ca[1]:.1f} {tip[0]:.1f} {tip[1]:.1f} Q{cb[0]:.1f} {cb[1]:.1f} {b[0]:.1f} {b[1]:.1f}'
    return d + ' Z'

def mirror(points, side):
    return [(512 + side * (x - 512), y) for x, y in points]

def path(points, close=True):
    d = f'M{points[0][0]:.0f} {points[0][1]:.0f}' + ''.join(f' L{x:.0f} {y:.0f}' for x, y in points[1:])
    return d + (' Z' if close else '')

def ear(side):
    return path(mirror([(448, 300), (406, 236), (352, 186), (300, 160), (296, 214), (278, 236),
                        (300, 262), (286, 300), (316, 330), (322, 380)], side))

def inner_ear(side):
    return path(mirror([(420, 300), (380, 246), (322, 196), (322, 262), (344, 330)], side))

def moustache(side):
    pts = [(512, 604), (486, 600), (456, 610), (430, 628), (404, 652), (424, 652), (396, 676),
           (430, 672), (414, 698), (452, 684), (446, 710), (478, 688), (488, 712), (512, 680)]
    return path(mirror(pts, side))

shadow = spiky(512, 508, 246, 236, 300, 30, 5, out=1.15)
head = spiky(512, 504, 236, 228, 288, 30, 9, out=1.10)
def brow(side):
    sx = lambda x: 512 + side * (x - 512)
    return (f'M{sx(380)} 438 Q{sx(424)} 410 {sx(476)} 404 Q{sx(490)} 410 {sx(484)} 424 '
            f'Q{sx(432)} 428 {sx(392)} 450 Z')

def fold(side):
    return path(mirror([(300, 160), (252, 196), (262, 214), (292, 214)], side))
